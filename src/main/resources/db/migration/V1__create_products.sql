CREATE TABLE PRODUCTS (
 ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 SKU VARCHAR2(50 CHAR) NOT NULL,
 NAME VARCHAR2(200 CHAR) NOT NULL,
 CATEGORY VARCHAR2(80 CHAR) NOT NULL,
 DESCRIPTION VARCHAR2(1000 CHAR),
 PRICE NUMBER(12,2) NOT NULL,
 RATING NUMBER(2,1),
 BADGE VARCHAR2(40 CHAR),
 IMAGE_URL VARCHAR2(1000 CHAR),
 ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
 CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT UK_PRODUCTS_SKU UNIQUE(SKU),
 CONSTRAINT CK_PRODUCTS_PRICE CHECK(PRICE>0),
 CONSTRAINT CK_PRODUCTS_RATING CHECK(RATING IS NULL OR (RATING>=0 AND RATING<=5)),
 CONSTRAINT CK_PRODUCTS_ACTIVE CHECK(ACTIVE IN (0,1))
);
CREATE INDEX IDX_PRODUCTS_CATEGORY_ACTIVE ON PRODUCTS(CATEGORY,ACTIVE);
CREATE INDEX IDX_PRODUCTS_NAME ON PRODUCTS(NAME);
